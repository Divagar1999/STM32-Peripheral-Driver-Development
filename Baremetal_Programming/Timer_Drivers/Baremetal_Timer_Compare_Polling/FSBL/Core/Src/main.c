static void GPIO_Init(void)
{
	/* Enable GPIOG clock */
	RCC ->AHB4ENR |= (0x1 << 6 );

	/* Configure PG8 as output mode */
	GPIOG ->MODER &= ~(0x3 << 8*2 );
	GPIOG ->MODER |=  (0x1 << 8*2 );

	/* Configure PG8 as push-pull */
	GPIOG ->OTYPER &= ~(0x1 << 8);

    /* Configure PG8 output speed */
    GPIOG->OSPEEDR &= ~(0x3 << 8*2 );

    /* Initially turn OFF LED */
	GPIOG ->BSRR |= (0x1 << 8);  // setting HIGH as default; LED is off by default

}

static void TIM9_Init(void)
{
	/* Enable TIM9 peripheral clock */
	RCC ->APB2ENR |= (0x1 << 19 );

	/* Stop TIM9 before configuration */
	TIM9 ->CR1 &= ~(0x1 << 0);

	/* Configure prescaler and auto-reload */
	TIM9 ->PSC = 19999;
	TIM9 ->ARR = 29999;

	/* Compare value CCR register value*/
	TIM9 ->CCR1 = 19999;

    /* Channel 1 as Output Compare */
    /* CC1S = 00 -> Output */
	TIM9 ->CCMR1 &= ~(0x3 << 0);

	/* OC1M = 000 -> Frozen mode */
	TIM9 ->CCMR1 &= ~(0x3 << 16);

	/* Disable OC1 preload */
	TIM9 ->CCER &= ~(0x1 << 3);

	/* Enable Channel 1 output compare channel */
	TIM9 ->CCER |= (0x1 << 0);

	/* Reset counter */
	TIM9 ->CNT = 0;

	/* Generate update event to load PSC */
	TIM9 ->EGR |= ( 0x1 << 0 );

	/* Clear update flag (UIF) and compare flag(CC1F)  */
	TIM9 ->SR &= ~( 0x3 << 0);

}

