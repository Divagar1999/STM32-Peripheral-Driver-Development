static void GPIO_Init(void)
{
	/* Enable GPIOG clock */
	RCC ->AHB4ENR |= (0x1 << 6 );

	/* Configure PG8 as output mode */
	GPIOG ->MODER &= ~(0x3 << 8*2 );
	GPIOG ->MODER |=  (0x1 << 8*2 );

	/* Configure PG8 as push-pull */
	GPIOG ->OTYPER &= ~(0x1 << 8);

    /* Configure PG8 output speed */
    GPIOG->OSPEEDR &= ~(0x3 << 8*2 );

    /* Initially turn OFF LED */
	GPIOG ->BSRR |= (0x1 << 8);  // setting HIGH as default; LED is off by default

}

static void TIM6_Init(void)
{
	/* Enable TIM6 peripheral clock */
	RCC ->APB1ENR1 |= (0x1 << 4 );

	/* Stop TIM6 before configuration */
	TIM6 ->CR1 &= ~(0x1 << 0);

	/* Configure prescaler and auto-reload */
	TIM6 ->PSC = 19999;
	TIM6 ->ARR = 29999;

	/* Reset counter */
	TIM6 ->CNT = 0;

	/* Generate update event to load PSC */
	TIM6 ->EGR |= ( 0x1 << 0 );

	/* Clear update flag */
	TIM6 ->SR &= ~( 0x1 << 0);

}

